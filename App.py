def _s(x) -> str:
    return (str(x or "").strip())

def norm_pot_name(x: str) -> str:
    s = _s(x)
    s = s.replace("ё", "е").replace("Ё", "Е")
    s = re.sub(r"\s{2,}", " ", s).strip()
    # Title-ish: "гранат" -> "Гранат"
    return s[:1].upper() + s[1:].lower() if s else s


