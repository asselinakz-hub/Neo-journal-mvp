def generate_extended_report(openai_client, model: str, profile: dict) -> str:
    """
    Сильный единый расширенный отчёт:
    - обращение на ВЫ
    - без Точка А/Б
    - без заданий/вопросов
    - опора на канон 1–9 (7–9 = коротко + что уменьшить)
    """
    f = (profile or {}).get("foundation", {}) or {}
    name = (f.get("name") or "Клиент").strip()
    matrix_raw = (f.get("potentials_table") or "").strip()

    if not matrix_raw:
        return "Ошибка: матрица потенциалов пустая. Сначала заполните потенциалы и сохраните основу."

    p9 = parse_potentials_9(matrix_raw)
    if len(p9) < 9:
        return (
            "Ошибка: не удалось извлечь 9 потенциалов.\n\n"
            "Вставьте 9 потенциалов (через запятую или нумерацией 1–9)."
        )

    # нормализуем имена (чтобы совпадали с ключами канона)
    p9 = [_pot_key(x) for x in p9[:9]]

    matrix_md = build_matrix_md(p9)
    canon_texts_1_9 = build_canon_texts_1_9_from_p9(p9)

    sys = build_unified_report_system_prompt_strong()
    user = build_unified_report_user_prompt_strong(
        name=name,
        matrix_md=matrix_md,
        p9=p9,
        canon_texts_1_9=canon_texts_1_9,
    )

    resp = openai_client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": sys},
            {"role": "user", "content": user},
        ],
        temperature=0.25,
    )
    return (resp.choices[0].message.content or "").strip()
